  add column source_archived_url text;

update published_version set
  headline            = library_entry->>'headline',
  accent              = library_entry->>'accent',
  dek                 = library_entry->>'dek',
  summary             = document->>'summary',
  page_title          = document->>'pageTitle',
  -- Lead patch: desk is editorial surface the frontend reads from library_entry today (library wins).
  -- Fall back to document for a hypothetical row with no library_entry desk.
  desk                = coalesce(library_entry->>'desk', document->>'desk'),
  authors             = coalesce(document->'paper'->>'authors', document->'blog'->>'organization'),
  year                = coalesce(document->'paper'->>'year', substring(document->'blog'->>'published' from 1 for 4))::int,
  trust               = coalesce(library_entry->>'trust', document->'blog'->>'trust'),
  minutes             = (library_entry->>'minutes')::int,
  role                = library_entry->>'role',
  note                = library_entry->>'note',
  source_url          = coalesce(document->'paper'->>'url', document->'blog'->>'url'),
  source_archived_url = document->'blog'->>'archivedUrl';

