-- ---------------------------------------------------------------------------
-- Sources: one row per distinct paper or post. (kind, url) identifies a source within its kind.
-- ---------------------------------------------------------------------------

create table source (
  id           bigint generated always as identity primary key,
  kind         text not null check (kind in ('paper', 'blog')),
  title        text not null,
  authors      text,
  year         int,
  url          text not null,
  organization text,  -- blog posts only
  trust        text check (trust in ('peer_reviewed', 'preprint', 'company_reported')),
  created_at   timestamptz not null default now()
);

create unique index source_kind_url_key on source (kind, url);

-- Archived copies (e.g. Wayback captures) of a source. Zero to many per source.
create table source_snapshot (
  id           bigint generated always as identity primary key,
  source_id    bigint not null,
  archived_url text not null,
  retrieved_on date not null,
  created_at   timestamptz not null default now()
);

create index source_snapshot_source_id_idx on source_snapshot (source_id);

-- ---------------------------------------------------------------------------
-- Tag vocabulary (mirrored from public/data/tags.json by the importer).
-- ---------------------------------------------------------------------------

create table facet (
  id         bigint generated always as identity primary key,
  key        text not null unique,  -- e.g. 'field', 'area', 'concept'
  label      text not null,
  position   int,
  created_at timestamptz not null default now()
);

create table tag (
  id         bigint generated always as identity primary key,
  key        text not null unique,  -- e.g. 'field/computer-science'
  facet_id   bigint not null,
  label      text not null,
  aliases    text[] not null default '{}',
  created_at timestamptz not null default now()
);

create index tag_facet_id_idx on tag (facet_id);

-- ---------------------------------------------------------------------------
-- Version-owned rows: each carries published_version_id.
-- ---------------------------------------------------------------------------

-- SVGs live under public/media/<slug>/. Unique per version by path; that index also serves lookups by version.
create table media_asset (
  id                   bigint generated always as identity primary key,
  published_version_id bigint not null,
  path                 text not null,
  kind                 text not null check (kind in ('svg', 'image', 'video')),
  width                int not null,
  height               int not null,
  alt                  text,
  created_at           timestamptz not null default now(),
  constraint media_asset_version_path_key unique (published_version_id, path)
);

-- One row per source-link appearance in the document.
create table citation (
  id                   bigint generated always as identity primary key,
  published_version_id bigint not null,
  source_id            bigint not null,
  anchor               text,  -- e.g. '§3.1' or '#S3.SS2'
  url                  text not null,
  label                text not null,
  context              text,
  created_at           timestamptz not null default now()
);

create index citation_published_version_id_idx on citation (published_version_id);
create index citation_source_id_idx on citation (source_id);

-- Which sources a version is built on. A version rewrite may change its sources.
create table story_source (
  id                   bigint generated always as identity primary key,
  published_version_id bigint not null,
  source_id            bigint not null,
  role                 text not null check (role in ('primary', 'secondary')),
  position             int,
  created_at           timestamptz not null default now()
);

create index story_source_published_version_id_idx on story_source (published_version_id);
create index story_source_source_id_idx on story_source (source_id);

-- A version's approved tags. Only approved tags reach published stories (the validator enforces it).
-- `source_kind` holds the tag's origin as PaperTag.source ('ai' or 'editor').
create table story_tag (
  id                   bigint generated always as identity primary key,
  published_version_id bigint not null,
  tag_id               bigint not null,
  relevance            numeric not null check (relevance between 0 and 1),
  basis                text not null check (basis in ('paper', 'background', 'editorial')),
  evidence             text,
  source_kind          text check (source_kind in ('ai', 'editor')),
  status               text not null check (status in ('suggested', 'approved')),
  created_at           timestamptz not null default now()
);

create index story_tag_published_version_id_idx on story_tag (published_version_id);
create index story_tag_tag_id_idx on story_tag (tag_id);

-- Front-page and feed bites (lead, hook, chapter, comic strip panel, fact), extracted from the document.
-- Decision 44: an illustration carries no source and no trust; every other claim carries trust.
create table moment (
  id                   bigint generated always as identity primary key,
  published_version_id bigint not null,
  key                  text not null,
  kind                 text not null check (kind in ('lead', 'hook', 'chapter', 'strip_panel', 'fact')),
  position             int,
  claim                text check (claim in ('illustration', 'model_design', 'measured_result')),
  trust                text check (trust in ('peer_reviewed', 'preprint', 'company_reported')),
  source_label         text,
  source_url           text,
  media_asset_id       bigint,  -- nullable: not every moment has media
  headline             text,
  text                 text,
  ref                  text,  -- anchor into the document
  created_at           timestamptz not null default now(),
  constraint moment_version_key_key unique (published_version_id, key),
  constraint moment_claim_trust_check check (
    claim is null
    or (claim = 'illustration' and trust is null)
    or (claim <> 'illustration' and trust is not null)
  )
);

create index moment_media_asset_id_idx on moment (media_asset_id);

-- One row per facts[].facts[] item in the document. `claim` is required on every fact (decision 44).
create table fact (
  id                   bigint generated always as identity primary key,
  published_version_id bigint not null,
  block_id             text not null,
  position             int,
  figure               text not null,
  claim                text not null check (claim in ('illustration', 'model_design', 'measured_result')),
  text                 text not null,
  source_label         text,
  source_url           text,
  media_asset_id       bigint,  -- nullable: not every fact has media
  created_at           timestamptz not null default now()
);

create index fact_published_version_id_idx on fact (published_version_id);
create index fact_media_asset_id_idx on fact (media_asset_id);

