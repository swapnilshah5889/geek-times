-- Supabase's default grants give anon and authenticated full privileges on new tables. Remove them.
revoke all on source, source_snapshot, facet, tag, media_asset, citation, story_source,
  story_tag, moment, fact
  from public, anon, authenticated;

-- Only the service role (the importer, server side) writes these tables.
grant select, insert, update, delete on source, source_snapshot, facet, tag, media_asset, citation,
  story_source, story_tag, moment, fact
  to service_role;

-- Identity sequences: the service role needs them to insert. Anon and authenticated get none.
revoke all on sequence source_id_seq, source_snapshot_id_seq, facet_id_seq, tag_id_seq,
  media_asset_id_seq, citation_id_seq, story_source_id_seq, story_tag_id_seq, moment_id_seq,
  fact_id_seq
  from public, anon, authenticated;

grant usage, select on sequence source_id_seq, source_snapshot_id_seq, facet_id_seq, tag_id_seq,
  media_asset_id_seq, citation_id_seq, story_source_id_seq, story_tag_id_seq, moment_id_seq,
  fact_id_seq
  to service_role;

-- The importer also writes the existing story and published_version tables. Grant it explicitly.
grant select, insert, update, delete on story, published_version to service_role;
grant usage, select on sequence story_id_seq, published_version_id_seq to service_role;

