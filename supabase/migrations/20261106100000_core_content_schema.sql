  add column year                int,
  add column trust               text check (trust in ('peer_reviewed', 'preprint', 'company_reported')),
  add column minutes             int,
  add column role                text check (role in ('lead', 'feature', 'brief', 'vault', 'real_world')),
  add column note                text,
