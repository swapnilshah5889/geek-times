-- Contract: docs/handoffs/v1-schema-contract.md (Agent A). Decisions 30, 34, 35, 38, 42, 44, 48.
--
-- Additive only: adds `story.sample`, adds metadata columns to `published_version`, and creates ten
-- new tables. Nothing is dropped, renamed or re-typed. The init migration is not touched.
-- `story_field` is not here: the contract lists it under Agent B (20261106100001_editorial_schema.sql).
--
-- No foreign keys (decisions 30 and 38). Every `*_id` column holds another row's numeric id and is
-- indexed; a unique constraint whose first column is `published_version_id` also serves that index.
-- Integrity comes from the one-transaction importer (Agent C), the unique / check / not-null
-- constraints here, and the orphan audit at the end of this file.
-- Enumerations are `text CHECK (col IN (...))`, not Postgres enums. Primary keys are identity columns.

