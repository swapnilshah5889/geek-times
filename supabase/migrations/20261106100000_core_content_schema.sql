-- ---------------------------------------------------------------------------
-- published_version metadata.
--
-- Strategy: add the columns nullable, backfill the existing rows from their own JSON in this same
-- transaction, then SET NOT NULL. No column gets a default, so no empty string or 0 can stand in for
-- a missing value. Sources of the backfill: `document` (the PaperDoc) for summary, page_title, desk,
-- authors, year and source_url (blog documents keep those under `blog`); `library_entry` (the
-- transitional LibraryStory) for headline, accent, dek, trust, minutes, role and note.
-- If a required value is missing on an existing row, SET NOT NULL fails and the whole migration
-- rolls back. Fix the backfill for that row; do not add a default.
-- ---------------------------------------------------------------------------

-- Lead patch: the init migration's `story.kind` CHECK is paper|blog only. library.json has stories
-- with kind="classic" (sample rows). Expand the CHECK so sample placeholder story rows land. The
-- constraint name was auto-generated by the init migration; look it up and recreate.
do $$
declare v_name text;
begin
  select conname into v_name from pg_constraint where conrelid = 'public.story'::regclass and contype = 'c'
    and pg_get_constraintdef(oid) ilike '%kind%paper%blog%';
  if v_name is null then raise exception 'story.kind CHECK not found'; end if;
  execute format('alter table public.story drop constraint %I', v_name);
end $$;
alter table story add constraint story_kind_check check (kind in ('paper', 'blog', 'classic'));

